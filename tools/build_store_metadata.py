"""Verifies the App Store copy in docs/store/listing/*.txt and writes docs/store/metadata.md from it.

The .txt files are the single source of truth (paste them into App Store Connect as they are). This script fails
(non-zero exit) if a limit or a rule is broken, so the numbers in metadata.md are always computed, never typed.

Run: python tools/build_store_metadata.py
"""
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
LIST = ROOT / "docs/store/listing"
OUT = ROOT / "docs/store/metadata.md"

LIMITS = {"name": 30, "subtitle": 30, "promo": 170, "keywords": 100, "description": 4000, "whats-new": 4000, "review-notes": 4000}
REQUIRED_KEYWORDS = ["compress", "resize", "reduce", "mp4", "mkv", "convert"]
# other compressor / editor brands that must not appear (WhatsApp, Telegram etc. are named only as preset targets)
COMPETITORS = ["vidcompact", "video compress", "videoshrink", "handbrake", "clipchamp", "capcut", "inshot", "vsco",
               "panda", "compress videos", "video squeezer", "videoleap", "lightricks"]
STOP = {"a", "an", "the", "and", "or", "of", "to", "in", "on", "for", "with"}

BASE = "https://ecomswiftllc.github.io/shrinkly/"
FALLBACK_NAMES = ["Video Compressor & Resizer: Shrinkly", "Video Compressor: Shrinkly", "Compress Video Size: Shrinkly"]


def read(n):
    return (LIST / f"{n}.txt").read_text(encoding="utf-8").strip("\r\n")


def words(s):
    return {w for w in re.findall(r"[a-z0-9]+", s.lower()) if w not in STOP}


def stem(w):
    return w[:-1] if w.endswith("s") and len(w) > 3 else w


def main():
    t = {k: read(k) for k in LIMITS}
    errs = []
    for k, lim in LIMITS.items():
        if len(t[k]) > lim:
            errs.append(f"{k}: {len(t[k])} > {lim}")
    if t["name"] != "Video Compressor: Shrinkly":
        errs.append("name must be 'Video Compressor: Shrinkly' (keywords first, brand last, one colon)")
    kw = t["keywords"]
    if " " in kw or kw.endswith(",") or kw.startswith(","):
        errs.append("keywords: no spaces, no stray commas")
    kwl = kw.split(",")
    if len(set(kwl)) != len(kwl):
        errs.append("keywords: repeated keyword")
    for r in REQUIRED_KEYWORDS:
        if r not in kwl:
            errs.append(f"keywords: missing {r}")
    seen = {stem(w) for w in words(t["name"] + " " + t["subtitle"])}
    for w in kwl:
        if stem(w) in seen:
            errs.append(f"keywords: '{w}' already in name or subtitle")
    stems = [stem(w) for w in kwl]
    if len(set(stems)) != len(stems):
        errs.append("keywords: two keywords share a stem")
    blob = " ".join(t.values()).lower()
    for c in COMPETITORS:
        if re.search(rf"\b{re.escape(c)}\b", blob):
            errs.append(f"competitor brand named: {c}")
    if re.search(r"\bAI\b", " ".join(t.values())) or "artificial intelligence" in blob:
        errs.append("'AI' wording is not allowed (no model does the work)")
    for bad in ["best ", "#1", "number one", "award", "5-star", "five star", "guaranteed", "any video", "all formats", "every format"]:
        if re.search(rf"{re.escape(bad.strip())}", blob):
            errs.append(f"unprovable claim wording: {bad.strip()}")
    if "drm" not in t["description"].lower():
        errs.append("description must say DRM-protected video cannot be processed")
    if errs:
        print("STORE COPY CHECK FAILED")
        for e in errs:
            print(" -", e)
        sys.exit(1)

    def n(k):
        return f"{len(t[k])} of {LIMITS[k]}"

    md = f"""# Shrinkly: App Store listing (en-US)

Generated by `python tools/build_store_metadata.py` from `docs/store/listing/*.txt`. Edit those files, not this one.
Naming rule (owner, always): search keywords first, brand last, one colon. The check script enforced every number below.

| Field | Value | Characters |
|---|---|---|
| Name | {t['name']} | {n('name')} |
| Subtitle | {t['subtitle']} | {n('subtitle')} |
| Home screen name | Shrinkly | short on purpose, long names truncate |
| Promotional text | see below | {n('promo')} |
| Keywords | {t['keywords']} | {n('keywords')} |
| Description | see below | {n('description')} |
| What's New (1.0) | see below | {n('whats-new')} |
| Primary category | Photo & Video | |
| Secondary category | Utilities | |
| Price | Free, ads (AdMob banner on Home + opt-in rewarded ad before each save, share or export) | |
| Bundle id | com.ecomswift.shrinkly | |
| Team | N84NGN3KSH (Ecom Swift LLC) | |
| Copyright | 2026 Ecom Swift LLC | |
| Support URL | {BASE}support/ | |
| Marketing URL | {BASE} | |
| Privacy Policy URL | {BASE}privacy/ | |
| Terms of Use | {BASE}terms/ (add as a link in the description area or EULA field if wanted; Apple's standard EULA applies by default) | |
| Open-source licences | {BASE}licenses/ | |
| Platforms | iPhone and iPad (universal), iOS 17.0 or later | |

Fallback names if Apple says "{t['name']}" is taken: {'; '.join(f'"{x}" ({len(x)})' for x in FALLBACK_NAMES)}. Keep the keywords-first, brand-last pattern. (The SPEC's first candidate "Video Compressor & Resizer: Shrinkly" is 36 characters and does not fit the 30 limit.)

Subtitle: "{t['subtitle']}" uses only words that are not in the name (Reduce-style words, MB, WhatsApp, Email), so every word adds a search term. Alternatives that also fit 30: "Reduce MB for WhatsApp, Email" (29), "Shrink Size for WhatsApp, Mail" (30), "Resize Clips for Email & Chat" (29).

Keyword field rules, checked by code: no word repeated from the name or subtitle, no spaces after commas, no repeated stem, no other app's brand, includes compress, resize, reduce, mp4, mkv and convert. Third-party service names (Telegram, Discord, TikTok and so on) are deliberately NOT in the keyword field, only WhatsApp and Email are in the subtitle at the owner's request. Apple can reject another company's trademark used as a keyword (guideline 2.3.7); if the subtitle is flagged, use "Reduce MB, Send by Email" style copy without WhatsApp.

## Promotional text ({n('promo')})

```
{t['promo']}
```

## Description ({n('description')})

Honest wording: no star or review claims, no competitor app names, no "AI", no claim that every file or protected video works, and the ad model stated plainly. WhatsApp, Telegram, Discord, TikTok and so on appear only as names of presets and the description says that limits change.

```
{t['description']}
```

Facts behind the wording (re-verify against the shipped build before every submission and edit the copy if a feature was cut): target size by slider and MB field with live estimate, quality mode, nine presets (WhatsApp, Telegram, Discord, Email 25 MB, Instagram/Reels, TikTok, X, YouTube Shorts, Messages), batch queue with a "You saved" total, before/after size and side-by-side compare, H.264 or HEVC, resolution, fps, audio, metadata strip, trim, FFmpeg reading of MKV/AVI/WebM/WMV/FLV/MPEG/TS, never overwrites the original, delete-original prompt after save, four built-in sample clips (`Sources/Resources/Samples`), banner on Home and one opt-in rewarded ad per export (batch = one ad). If trim, the delete-original prompt, "Try a sample clip" or any preset is not in the first build, remove it from the description and review notes.

## What's New, version 1.0 ({n('whats-new')})

```
{t['whats-new']}
```

## App Review notes ({n('review-notes')})

```
{t['review-notes']}
```

Contact for review (App Store Connect form): the owner's name, phone and the support address. Sign-in required: No (do not tick it, no demo account).

## Age rating answers (Apple's questionnaire)

Expected result: 4+.

- In-app controls: Parental Controls No. Age Assurance No.
- Unrestricted Web Access: No. (The app does not embed a browser. Ads can open a website in Apple's system browser sheet, which is normal for ad SDKs.)
- User-Generated Content: No. Messaging and Chat: No. Advertising: Yes (Google AdMob, banner and rewarded video).
- Content descriptors, all None: Cartoon or Fantasy Violence, Realistic Violence, Prolonged Graphic or Sadistic Violence, Profanity or Crude Humor, Mature or Suggestive Themes, Horror or Fear Themes, Medical or Treatment Information, Alcohol Tobacco or Drug Use or References, Simulated Gambling, Sexual Content or Nudity, Contests, Gambling.
- Health or Wellness Topics: No.
- In AdMob set the maximum ad content rating to General (or Parental Guidance) and block sensitive categories, so the ads match the 4+ rating.

## App Privacy (nutrition label)

See `docs/store/app-privacy.md`. Summary: tracking Yes (Device ID, Advertising Data); Product Interaction and Performance Data collected and linked, not used for tracking; Coarse Location and Crash Data not linked. No photos or videos are collected.

## Export compliance and other forms

- Encryption: the app uses HTTPS through system and Google SDK networking. FFmpeg is linked but no app-level encryption is added. Answer "uses standard encryption" and exempt unless the owner or a lawyer decides FFmpeg's built-in crypto (AES, TLS for network inputs) changes that; the main session owns `ITSAppUsesNonExemptEncryption` in Info.plist. Verify before submitting.
- Content rights: the four sample clips come from Pexels under the Pexels License (`docs/store/media-credits.md`). Answer Yes to "contains third-party content" with the right to use it. FFmpeg and codec libraries are open source (LGPL / BSD), notices in Settings and on the licences page.
- Digital Services Act trader status: Ecom Swift LLC as a trader, using the address and phone on the owner's Apple account.
- Sign in required: No.

## Screenshots

`python tools/make_store_shots.py <CI screenshots> design/store/6.9` (6.9-inch, 1290 x 2796) and
`python tools/make_store_shots_ipad.py <CI screenshots-ipad> design/store/ipad13` (13-inch iPad, 2064 x 2752).
Capture names: home-filled, setup-target, setup-presets, setup-advanced, processing, result, compare, batch, formats, settings.
Slides use real captures only; missing captures are skipped. Slide copy is in `tools/store_shots_common.py`.

## Localisation

Optional, later, same pattern in each language: translated keywords first, then ": Shrinkly" (es, fr, de, zh-Hans first).
"""
    OUT.write_text(md, encoding="utf-8")
    print("store copy OK")
    for k in LIMITS:
        print(f"  {k}: {len(t[k])}/{LIMITS[k]}")
    print("wrote", OUT)


if __name__ == "__main__":
    main()
